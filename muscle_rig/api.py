"""One-call entry points used by the UI, the Rigify finalize hook and tests."""

import bpy

from . import build, bulge, jiggle, weights
from .library import SETS

HOOK_TEXT = "muscle_rig_finalize.py"


def bound_meshes(rig):
    """Meshes whose Armature modifier points at ``rig``."""
    return [o for o in bpy.data.objects if o.type == 'MESH' and any(
        m.type == 'ARMATURE' and m.object == rig for m in o.modifiers)]


def apply(rig, set_names=("arm",), meshes=None, add_jiggle=True, **jiggle_settings):
    """Build muscle bones, paint masks, add bulge (+ jiggle) in one go.

    Safe to call repeatedly, e.g. after regenerating the Rigify rig: bones,
    masks, drivers and modifiers are all rebuilt from scratch. The meshes'
    own skin weights are never modified.

    Returns ``(built, painted)`` where ``painted`` maps mesh name ->
    {mask name: (vertex count, push amplitude)}.
    """
    sets = [SETS[n] for n in set_names]
    built = build.build_muscles(rig, sets)
    painted = {}
    for mesh in (bound_meshes(rig) if meshes is None else meshes):
        weights.paint_masks(mesh, rig, built)
        painted[mesh.name] = _bind(mesh, rig, built, add_jiggle, jiggle_settings)
    return built, painted


def rebind(rig, meshes=None, add_jiggle=True, **jiggle_settings):
    """Re-bake hand-edited ``MUS-*`` vertex groups without repainting them."""
    built = [(spec, side) for name in rig.get("muscle_rig_sets", "").split(",") if name in SETS
             for spec in SETS[name].muscles for side in SETS[name].sides
             if spec.bone_names(side)[0] in rig.data.bones]
    return {mesh.name: _bind(mesh, rig, built, add_jiggle, jiggle_settings)
            for mesh in (bound_meshes(rig) if meshes is None else meshes)}


def _bind(mesh, rig, built, add_jiggle, jiggle_settings):
    order, info = weights.bake_masks(mesh, rig, built)
    bulge.add_bulge(mesh, rig, order, info)
    if add_jiggle:
        jiggle.add_jiggle_modifier(mesh, **jiggle_settings)
    else:
        jiggle.remove_jiggle_modifier(mesh)
    return info


def strip(rig, meshes=None):
    """Remove every trace of the muscle system from the rig and its meshes."""
    for mesh in (bound_meshes(rig) if meshes is None else meshes):
        bulge.remove_bulge(mesh)
        jiggle.remove_jiggle_modifier(mesh)
        weights.clear_masks(mesh)
    build.remove_muscles(rig)


_HOOK_TEMPLATE = '''# Auto-generated by the Muscle Rig add-on. Rigify runs this right after
# generating, with the new rig active, so the muscles come back on every
# regenerate. Delete this text (or clear "Run Script") to stop it.
import sys
import bpy

SETS = {sets!r}

api = None
for name, module in list(sys.modules.items()):
    if name.endswith("muscle_rig.api") and hasattr(module, "apply"):
        api = module
        break
rig = bpy.context.active_object
if api is None:
    print("[muscle_rig] add-on not enabled; muscles were not rebuilt")
elif rig is not None and rig.type == 'ARMATURE':
    api.apply(rig, SETS)
'''


def install_rigify_hook(metarig, set_names):
    """Point the metarig's Rigify "Run Script" at a text that rebuilds muscles."""
    text = bpy.data.texts.get(HOOK_TEXT) or bpy.data.texts.new(HOOK_TEXT)
    text.clear()
    text.write(_HOOK_TEMPLATE.format(sets=tuple(set_names)))
    metarig.data.rigify_finalize_script = text
    return text
